#define FONT_TABLE_SIZE (sizeof(font_table) / sizeof(font_table[0]))

/* find_glyph used to linear-scan all ~75 entries for every single
   character of every string drawn (window titles, button labels, file
   names, the clock, ...) - which happens a lot every frame. Built once,
   lazily, into a direct 128-entry lookup instead: O(1) per character. */
static glyph_t *ascii_lookup[128];
static bool ascii_lookup_built = false;

static void build_ascii_lookup(void) {
    for (int i = 0; i < 128; i++) ascii_lookup[i] = NULL;
    for (uint32_t i = 0; i < FONT_TABLE_SIZE; i++) {
        uint8_t c = (uint8_t)font_table[i].c;
        if (c < 128) ascii_lookup[c] = (glyph_t*)&font_table[i].rows;
    }
    ascii_lookup_built = true;
}

static glyph_t *find_glyph(char c) {
    if (!ascii_lookup_built) build_ascii_lookup();
    uint8_t uc = (uint8_t)c;
    return (uc < 128) ? ascii_lookup[uc] : NULL;
}

void font_get_glyph_bitmap(char c, uint8_t out[7][5]) {
    glyph_t *glyph = find_glyph(c);
    for (int32_t row = 0; row < GLYPH_H; row++) {
        for (int32_t col = 0; col < GLYPH_W; col++) {
            out[row][col] = (glyph && (*glyph)[row][col] == '#') ? 1 : 0;
        }
    }
}

void font_draw_char(int32_t x, int32_t y, char c, uint32_t color, int32_t scale) {
    glyph_t *glyph = find_glyph(c);
    if (!glyph) {
        /* Unknown but printable character: draw a small placeholder box so
           typing always gives visible feedback instead of silently vanishing. */
        if (c > ' ' && c < 127) {
            for (int32_t i = 0; i < GLYPH_W; i++) {
                fb_fill_rect(x + i * scale, y, scale, scale, color);
                fb_fill_rect(x + i * scale, y + (GLYPH_H - 1) * scale, scale, scale, color);
            }
            for (int32_t j = 0; j < GLYPH_H; j++) {
                fb_fill_rect(x, y + j * scale, scale, scale, color);
                fb_fill_rect(x + (GLYPH_W - 1) * scale, y + j * scale, scale, scale, color);
            }
        }
        return;
    }

    for (int32_t row = 0; row < GLYPH_H; row++) {
        const char *line = (*glyph)[row];
        for (int32_t col = 0; col < GLYPH_W; col++) {
            if (line[col] == '#') {
                fb_fill_rect(x + col * scale, y + row * scale, scale, scale, color);
            }
        }
    }
}

void font_draw_string(int32_t x, int32_t y, const char *s, uint32_t color, int32_t scale) {
    int32_t cursor_x = x;
    while (*s) {
        font_draw_char(cursor_x, y, *s, color, scale);
        cursor_x += (GLYPH_W + 1) * scale;
        s++;
    }
}

int32_t font_string_width(const char *s, int32_t scale) {
    int32_t len = 0;
    while (s[len]) len++;
    if (len == 0) return 0;
    return len * (GLYPH_W + 1) * scale - scale;
}

int32_t font_char_height(int32_t scale) {
    return GLYPH_H * scale;
}
